    private void btnSign1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSign1ActionPerformed
        
        String email = txtEmail.getText(); 
        String senha = txtSenha.getText();
        
        if (email.equalsIgnoreCase("") || senha.equalsIgnoreCase("")) {
            JOptionPane.showMessageDialog(null, "Preencha todos os campos!", "ERROR", JOptionPane.ERROR_MESSAGE);  
            return;
        }

        Usuario u = new Usuario();
        u.setEmail(email);
        u.setSenha(senha);
            
        if (UsuarioDAO.autentificarUsuario(u) != null) {
            JOptionPane.showMessageDialog(null, "Login com sucesso!","SUCESSO", JOptionPane.INFORMATION_MESSAGE);
            TelaInicio ti = new TelaInicio(UsuarioDAO.autentificarUsuario(u));
            ti.setVisible(true);
        }
        else {
            JOptionPane.showMessageDialog(null, "Email ou senha incorretos", "ERROR", JOptionPane.ERROR_MESSAGE);  
        }
    }//GEN-LAST:event_btnSign1ActionPerformed

