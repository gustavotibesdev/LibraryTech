    private void btnSignActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSignActionPerformed
       
        String nome = txtNome.getText();
        String email = txtEmail.getText();
        String senha = txtSenha.getText();
        String endereco = txtSenha.getText();
        String contato = txtSenha.getText();
        
        String defaultPermissao = "Cliente";
        
        if (nome.equalsIgnoreCase("") || senha.equalsIgnoreCase("") || email.equalsIgnoreCase("") || endereco.equalsIgnoreCase("") || contato.equalsIgnoreCase("")) {
            JOptionPane.showMessageDialog(null, "Preencha todos os campos!", "ERROR", JOptionPane.ERROR_MESSAGE);
        }
        else {
            
            // Decidi colocar todos os novos usuários que serão cadastrados com a permissão cliente;
            
            Cliente c = new Cliente(endereco,contato,nome,email,senha,defaultPermissao);
            ClienteDAO.cadastrarCliente(c);
            
            JOptionPane.showMessageDialog(null, "Cadastrado com sucesso!", "SUCESSO", JOptionPane.INFORMATION_MESSAGE);
                    
        }        
    }//GEN-LAST:event_btnSignActionPerformed

