    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        
        String titulo = txtTitulo.getText();
        String autor = txtAutor.getText();
        String genero = (String) cmbGenero.getSelectedItem();
        String anoStg = txtAno.getText();
        
        if (titulo.isEmpty() || autor.isEmpty() || genero.isEmpty() || anoStg.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Preencha todos os campos","ERROR",JOptionPane.ERROR_MESSAGE);
        }
        else {
            
            int ano = Integer.parseInt(anoStg);
            
            Livro l = new Livro(titulo,autor,genero,ano);
            LivroDAO ldao = new LivroDAO();
            ldao.cadastrarLivro(l);
            
            iniciarTabela();
        }
  
    }//GEN-LAST:event_btnCadastrarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        
        int linhaSelecionada = jTable1.getSelectedRow();
        
        if (linhaSelecionada != -1) {
            int id = (int) jTable1.getValueAt(linhaSelecionada, 0);
            LivroDAO.excluirLivro(id);
            iniciarTabela();
        }
        
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void iniciarTabela() {
    
        Object[] colunas = {
            "ID",
            "TÍTULO",
            "GÊNERO",
            "AUTOR",
            "ANO",
        };
        
        if (tableModel == null) {
            
            tableModel = new DefaultTableModel(colunas,0);
            
            jTable1.setModel(tableModel);
            
        }
        
        tableModel.setRowCount(0);
        
        for (Livro l : LivroDAO.mostrarLivros()) {
            tableModel.addRow(new Object[] {
                l.getIdLivro(),
                l.getTitulo(),
                l.getAutor(),
                l.getGenero(),
                l.getAno()
            });
        }
        
    }
    
