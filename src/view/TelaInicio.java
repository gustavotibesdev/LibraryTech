    public void iniciarTabela(List<Livro> lista) {
    
        Object[] colunas = {
            "ID",
            "TÍTULO",
            "GÊNERO",
            "AUTOR",
            "ANO"
        };
        
        if (tableModel == null) {
        
            tableModel = new DefaultTableModel(colunas,0);
            
            jTable1.setModel(tableModel);
            
        }
        
        tableModel.setRowCount(0);
        
        for (Livro l : lista) {
            tableModel.addRow(new Object[] {
                l.getIdLivro(),
                l.getTitulo(),
                l.getAutor(),
                l.getGenero(),
                l.getAno()
            });
        }
        
    }

